  - `{{TASKS}}` — задачи сотрудника с активностью за последние 7 дней
  - `{{MEETINGS}}` — встречи сотрудника на сегодня

  Структура задачи: TITLE, STATUS (читаемая строка — название стадии), ACTIVITY_DATE, DEADLINE, RESPONSIBLE, CREATOR, CHAT_INFO, IS_OVERDUE, URL, PRIORITY (0=низкий, 1=средний, 2=высокий), PROJECT_NAME (null если задача вне проекта).

