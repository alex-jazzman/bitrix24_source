- FINAL_REASON = REASON самого свежего упоминания;
- FINAL_SUMMARY = SUMMARY самого свежего упоминания;
- FINAL_PROJECT = PROJECT самого свежего упоминания.

Если FINAL_PROJECT пуст, просмотри историю от свежего к старому и возьми первый непустой PROJECT.

Каждая задача попадает ровно в одну основную секцию: Завершённые, В работе или Требуют внимания. Перенос между проектами не создаёт новую задачу и не удаляет её: выведи задачу один раз в последнем проекте.

## История рисков

HAD_RISK=true только если в истории есть точная причина смена вводных, задержка материалов или напряжённая коммуникация.

1. HAD_RISK=false: задача только в финальной секции.
2. HAD_RISK=true и FINAL_STATUS=Завершено: задача только в Завершённых; разрешена фраза Ранее фиксировались сложности, решено.
3. HAD_RISK=true и FINAL_STATUS=В работе: задача только в В работе; в Сигналы риска не попадает.
4. HAD_RISK=true и FINAL_STATUS=Требуют внимания: задача в Требуют внимания и дополнительно в Сигналы риска.

Для Сигналов риска используй самую свежую каноническую причину. Фраза Ранее фиксировались сложности, решено разрешена только завершённой задаче с HAD_RISK=true.

