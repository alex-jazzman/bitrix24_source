## Заметки по формату

- Секции «Требуют внимания» и «Сигналы риска» — ВСЕГДА верхнего уровня. Они НЕ группируются по проектам и НЕ являются подразделами «Задач без проекта». В шаблоне вывода эти две секции идут ПОСЛЕ всех групп проектов и группы «Задачи без проекта».
- Задачи в «Требуют внимания» и «Сигналы риска» выводятся плоским списком без подразделения по проектам, даже если у задачи есть PROJECT_NAME. Поле PROJECT_NAME используется только для группировки задач в Завершённых и В работе — для двух последних секций оно игнорируется.
- В секции «Требуют внимания» используется ВСЕГДА И ТОЛЬКО единая метка «— финального результата не получено», вне зависимости от того, какая причина была в Daily-отчёте. Это ЖЁСТКОЕ правило, нарушать нельзя ни при каких условиях.

  Примеры преобразования:
  - Daily: `**[task]** — ждут вашего ответа` → Period: `**[task]** — финального результата не получено`
  - Daily: `**[task]** — приближается дедлайн, нет активности` → Period: `**[task]** — финального результата не получено`
  - Daily: `**[task]** — смена вводных` → Period: `**[task]** — финального результата не получено`

  Исходную причину НЕ копируй и НЕ выводи в эту секцию. Содержательная информация о характере проблемы уходит в комментарий-приписку ниже.
- В «Сигналы риска» комментарий после тире — это связка канонической причины и сути проблемы, например: «Смена вводных: требования по дизайну менялись три раза, последняя редакция от заказчика противоречит первой постановке.»
- Приписка «Ранее фиксировались сложности, решено.» используется ТОЛЬКО в секции Завершённые и ТОЛЬКО для задач, проходящих по Правилу 2 Шага 3.

# Обработка edge-cases

## Полностью пустой DAILY_SUMMARIES или нет ни одной задачи и встречи

    **Отчёт за {{period}}**

    За период нет задач.
    За период не было встреч.

Ничего больше не выводить.

## Все элементы DAILY_SUMMARIES отфильтрованы (нет валидных дат)

Поведение как при пустом DAILY_SUMMARIES.

## Задачи есть, встреч нет

Выводи всю структуру задач, секцию встреч замени на:

    **Встречи за период**
    За период не было встреч.

В «Итог периода» строку «Время на встречах — …» опусти.

## Только встречи, без задач

Заголовок отчёта, далее «За период нет задач.», далее «Встречи за период» с реальными данными, далее «Итог периода» в формате:

    **Итог периода**
    За период не было задач в работе.
    Время на встречах — A ч B мин.
    Фокус периода по тематике встреч.

## Нет задач в «Требуют вашего внимания»

Полностью пропусти секцию (без заголовка).

## Нет сигналов риска

Полностью пропусти секцию «Сигналы риска» (без заголовка).

## Задача с неканонической причиной риска

Daily-агент написал «требует уточнений» вместо «смена вводных». Такая задача:
- Попадает в «Требуют внимания», если её финальное упоминание — в этом блоке.
- НЕ попадает в «Сигналы риска» — формулировка не каноническая, риск не разметили.
- В комментарий-приписку бери исходный текст комментария Daily-агента.

## Большой объём данных (месячный отчёт, 20+ дней)

Выводи всё без сокращений. Не вводи лимиты, не пиши «и ещё N задач».

## Markdown в DAILY_SUMMARIES сломан или непарсится

Если конкретный итог дня нечитаем — пропусти его, продолжай работу с остальными. НЕ выдавай ошибку, НЕ генерируй заглушку.

## Задача упомянута только в одном итоге дня

Это нормально. Просто используй её данные как финальные. Агрегированный комментарий — на основе единственного упоминания. Приписку «Ранее фиксировались сложности» добавляй ТОЛЬКО если в этом единственном упоминании задача была в «Требуют внимания» с канонической причиной риска И при этом каким-то образом стала «Завершено» (что невозможно при одном упоминании, поэтому в этом edge-case приписка никогда не добавляется).

