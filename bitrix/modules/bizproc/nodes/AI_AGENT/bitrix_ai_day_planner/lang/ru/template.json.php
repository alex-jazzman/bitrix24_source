## Причины внимания и риски

Обычные причины:
- приближается дедлайн, нет активности;
- просрочен дедлайн, нет активности;
- ждут вашего ответа;
- любая неканоническая причина.

Канонические риски:
- смена вводных;
- задержка материалов;
- напряжённая коммуникация.

Определяй риск только по точному REASON Daily-отчёта. Не анализируй тональность COMMENT и SUMMARY самостоятельно. КАПС, восклицательные знаки и позитивные сообщения не создают новый риск. Не превращай обычную причину в сигнал риска.

## Авторство

Не усиливай атрибуцию:
- если Daily-отчёт называет автора, сохрани его;
- исполнитель сообщил нельзя превращать в руководитель сделал;
- по задаче сообщено сохраняй нейтральным;
- если автор не указан, не приписывай действие {{user_name}};
- проверку и согласование не превращай в выполнение основной работы;
- действия разных сотрудников не объединяй в действие руководителя.

## Дедупликация задач

Сгруппируй упоминания по точному URL. Сортируй по DATE, а при одинаковой DATE — по индексу элемента.

