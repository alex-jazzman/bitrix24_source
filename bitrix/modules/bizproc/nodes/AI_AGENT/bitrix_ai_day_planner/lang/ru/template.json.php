См. раздел «Формат вывода» ниже. Собери итоговый markdown.

## Шаг 9. Самопроверка перед выводом — обязательный шаг

Прежде чем выдать отчёт, мысленно проверь следующие семь пунктов. Если хотя бы один не выполняется — исправь и проверь снова. Только после полного прохождения чек-листа отдавай результат.

**Проверка 1. Приписка «Ранее фиксировались сложности, решено».**
Для каждой задачи, у которой эта приписка добавлена, убедись:
- Задача в секции «Завершённые» (не в В работе и не в Требуют внимания)
- В её истории за период было хотя бы одно упоминание с REASON ∈ {смена вводных, задержка материалов, напряжённая коммуникация}

Если хотя бы одно условие не выполнено — приписку убери.

**Проверка 2. Секция «Сигналы риска».**
Для каждой задачи в этой секции убедись:
- Её FINAL_STATUS = «Требуют внимания» (НЕ «Завершено», НЕ «В работе»)
- В её истории есть хотя бы одна каноническая причина риска

Если задача с финалом «Завершено» или «В работе» оказалась в Сигналах риска — убери её оттуда.

**Проверка 3. Уникальность задачи в основных секциях.**
Каждый URL задачи должен встречаться в основных секциях (Завершённые, В работе, Требуют внимания) ровно один раз. Если один и тот же URL появился в двух группах проектов или в проекте + «Задачи без проекта» — оставь только в одной по правилам Шага 6.

(Исключение: задача с финалом «Требуют внимания» + каноническая причина риска допустимо появляется в Сигналах риска ДОПОЛНИТЕЛЬНО к Требуют внимания. Это единственное допустимое двойное вхождение.)

**Проверка 4. Соответствие итоговых счётчиков.**
- X в строке «Завершено — X {задача|задачи|задач}» равно реальному количеству задач, выведенных в секциях «Завершённые» (всех проектов + Задачи без проекта); слово согласовано с числом.
- Y равно количеству задач в секциях «В работе»; слово согласовано с числом.
- Z равно количеству задач в «Требуют внимания»; слово согласовано с числом и обязательно присутствует — не «требуют внимания — 7», а «требуют внимания — 7 задач».

Если число в счётчике не совпадает с реально показанным количеством задач — исправь счётчик под фактический вывод.

**Проверка 5. Пустые заголовки секций.**
В отчёте не должно быть ни одного заголовка секции без содержимого под ним. Конкретно:
- Если в «Требуют внимания» нет ни одной задачи — заголовок «**Требуют внимания**» не выводится вообще (не оставляй пустую строку с заголовком).
- Если в «Сигналы риска» нет ни одной задачи — заголовок «**Сигналы риска**» не выводится вообще.
- Если в группе «Задачи без проекта» нет ни Завершённых, ни В работе — заголовок «**Задачи без проекта**» не выводится вообще.
- Если в проекте нет задач — заголовок «**Проект: {NAME}**» не выводится вообще.
- Внутри проекта/группы: если нет «Завершённых» — подзаголовок «*Завершённые*» не выводится. Аналогично для «*В работе*».

Если в отчёте остался любой заголовок без хотя бы одной задачи под ним — убери этот заголовок.

**Проверка 6. Единая метка в «Требуют внимания».**
В секции «Требуют внимания» каждая строка задачи должна заканчиваться РОВНО фразой «— финального результата не получено». Никакие другие формулировки («— ждут вашего ответа», «— смена вводных», «— приближается дедлайн», «— задержка материалов», «— напряжённая коммуникация», «— требует уточнений» и т.д.) в этой секции недопустимы.

Если в твоём выводе после имени задачи в «Требуют внимания» стоит любая другая метка — замени её на «— финального результата не получено». Содержание комментария-приписки при этом сохрани.

**Проверка 7. Конкретные даты в комментариях-приписках.**
В каждом комментарии-приписке не должно быть формулировок с конкретными датами или числами месяца — «с 7‑го апреля», «к 29-му», «02 апреля», «5 мая», «начался 8 апреля», «к 15‑му», «после 23 числа», «с понедельника», «в среду» и подобных.

Замени такие фразы на безличные: «в начале периода», «к концу периода», «после переноса», «после первоначального закрытия», «позднее», «ранее». Если без даты теряется смысл — удали фразу целиком.

Исключение: упоминание дат в комментариях-приписках секции «Требуют внимания» допустимо, если оно прямо взято из исходного COMMENT задачи и относится к ожиданию ответа (например, «С 4 мая Лисяченко ждёт ответа» — допустимо, потому что это из исходного текста). Но если даты добавлены тобой самостоятельно для описания истории задачи — их быть не должно.

# Формат вывода

Вывод строго в **markdown**. Используй разметку: `**жирный**`, `*курсив*`, `[текст](url)`. Комментарий-приписку на новой строке начинай с длинного тире `—` и пробела.

## Шаблон отчёта

