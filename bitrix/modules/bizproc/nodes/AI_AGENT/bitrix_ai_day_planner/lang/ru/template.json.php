# Алгоритм

Выполняй шаги строго по порядку.

## Шаг 1. Извлечение задач и встреч из каждого итога дня

Перед обработкой отфильтруй массив `DAILY_SUMMARIES`:
- Пропусти элементы, у которых `date` отсутствует, равно `null` или пустой строке.
- Если в массиве несколько элементов с одинаковой `date` — обрабатывай их все как несколько упоминаний этого дня; при сортировке по дате (Шаг 2) их относительный порядок определяется порядком в исходном массиве (более поздний по индексу = более свежий).

Для каждого валидного элемента `DAILY_SUMMARIES[i]` распарси `text` и извлеки:

**Список задач**, для каждой:
- `URL` — уникальный ключ задачи (из `[Название](URL)`)
- `TITLE` — название задачи
- `PROJECT` — название проекта или `null` (если задача в секции «Задачи без проекта»)
- `SECTION` — одно из: `\"Завершено\"`, `\"В работе\"`, `\"Требуют внимания\"`
- `REASON` — причина для «Требуют внимания» (текст после тире), для других секций — `null`
- `SUMMARY` — текст резюме после задачи (для «Завершено» / «В работе»)
- `COMMENT` — текст комментария-приписки на следующей строке после задачи (начинается с `— ` в новом формате end-of-day или с `↳ ` в старых итогах дня — поддерживай оба варианта), для «Требуют внимания», если есть
- `DATE` — `date` из обёртки `DAILY_SUMMARIES[i]`

**Список встреч**, для каждой:
- `TITLE` — название встречи
- `START_TIME`, `END_TIME` — время начала и конца (HH:MM)
- `URL` — ссылка на встречу
- `PARTICIPANTS` — массив ФИО
- `DATE` — `date` из обёртки

## Шаг 2. Дедупликация задач по URL — правило «последнее упоминание»

Сгруппируй все задачи по `URL`. Для каждой уникальной задачи:

1. Отсортируй её упоминания по `DATE` от старого к свежему.
2. **FINAL_STATUS** = `SECTION` самого свежего упоминания.
3. **FINAL_REASON** = `REASON` самого свежего упоминания (только если FINAL_STATUS = «Требуют внимания»).
4. **FINAL_PROJECT** = `PROJECT` самого свежего упоминания (см. Шаг 6 для уточнений).
5. **FINAL_SUMMARY** = `SUMMARY` или `COMMENT` самого свежего упоминания.

Для последующих шагов также запомни ВСЮ историю упоминаний задачи (понадобится для Шагов 3, 4).

## Шаг 3. Определение сигналов риска — дерево решений

Для каждой уникальной задачи выполни ДВЕ независимые проверки.

### Проверка А: имела ли задача канонический сигнал риска КОГДА-ЛИБО?

Просканируй ВСЕ упоминания задачи (включая историю, не только финал). Если хотя бы в одном из упоминаний `REASON` был одним из трёх канонических:
- `смена вводных`
- `задержка материалов`
- `напряжённая коммуникация`

→ установи флаг **HAD_RISK = да**.

Иначе → **HAD_RISK = нет**.

ВАЖНО: неканонические причины (например, «требует уточнений», «приближается дедлайн», «ждут вашего ответа») НЕ устанавливают HAD_RISK.

### Проверка Б: применение правил по дереву решений

Используй следующее дерево (читай сверху вниз, применяй ПЕРВОЕ подходящее правило, остальные не проверяй):

**ПРАВИЛО 1: HAD_RISK = нет.**
→ Задача в Сигналы риска НЕ попадает.
→ Приписку «Ранее фиксировались сложности, решено» в её резюме НЕ добавляй.
→ Идёт в свою основную секцию (Завершённые / В работе / Требуют внимания) с обычным резюме.
→ Обработка задачи завершена. К следующему правилу не переходи.

**ПРАВИЛО 2: HAD_RISK = да И FINAL_STATUS = «Завершено».**
→ Задача в Сигналы риска НЕ попадает.
→ Идёт в Завершённые. К FINAL_SUMMARY добавь приписку «Ранее фиксировались сложности, решено.»

**ПРАВИЛО 3: HAD_RISK = да И FINAL_STATUS = «В работе».**
→ Задача в Сигналы риска НЕ попадает.
→ Идёт в В работе с обычным резюме.
→ В комментарии-приписке можно упомянуть, что были сложности (теперь стабилизировано). Но приписку «Ранее фиксировались сложности, решено» в строке резюме НЕ добавляй — она только для Завершённых.

**ПРАВИЛО 4: HAD_RISK = да И FINAL_STATUS = «Требуют внимания».**
→ Задача идёт в Требуют внимания.
→ Также попадает в Сигналы риска с самой свежей канонической причиной из её истории.
→ Самая свежая каноническая причина = последнее по времени упоминание задачи, у которого `REASON` ∈ {смена вводных, задержка материалов, напряжённая коммуникация}. Может отличаться от `FINAL_REASON`, если в финальном упоминании причина была неканонической.

### Анти-правило (повторение для надёжности)

Приписка «Ранее фиксировались сложности, решено» добавляется ТОЛЬКО когда HAD_RISK = да И FINAL_STATUS = Завершено. Никогда не добавляй её к задачам без канонической причины риска в истории, даже если задача проделала путь от В работе к Завершено.

## Шаг 4. Агрегированные комментарии (приписка через длинное тире)

Для каждой задачи в секциях «В работе» и «Требуют внимания» нужен комментарий-приписка на новой строке, начинающаяся с длинного тире `—` и пробела. Символ `↳` не используем.

Правила формирования комментария:
- Соедини ключевые факты из всех упоминаний задачи в DAILY_SUMMARIES (бери `SUMMARY` для «В работе» и `COMMENT` для «Требуют внимания»).
- Опиши развитие за период, если оно было: «началось с X, к концу периода — Y».
- Длина 15–35 слов, одно предложение или два коротких.
- НЕ упоминай конкретные даты внутри комментария — хронология ясна из периода.
- Если задача упомянута в одном итоге дня — переформулируй исходный комментарий или используй его как есть.
- Если задача когда-то была сигналом риска, но финал не риск (Правило 3 из Шага 3) — в комментарии-приписке можешь упомянуть факт прошлых сложностей. Но приписку «Ранее фиксировались сложности, решено» в строку резюме при этом НЕ выводи.

## Шаг 5. Дедупликация встреч

Встречи могут повторяться (еженедельный stand-up, регулярная планёрка). Объединяй их в одну запись.

**Ключ дедупликации:** точное совпадение `TITLE` (с учётом регистра и пробелов).

Обоснование: URL у каждого экземпляра встречи свой (содержит дату), поэтому он не работает как идентификатор серии. Время может быть смещено на несколько минут от занятия к занятию (например, регулярная планёрка перенеслась с 14:00 на 14:15) — поэтому ключ по времени даёт ложно-разделённые записи. Совпадение названия в практическом большинстве случаев означает, что это одна и та же регулярная встреча. Ложно-объединённые случаи (две разных встречи с одинаковым названием в одном периоде) пренебрежимо редки.

Для дедуплицированной записи бери:
- `TITLE` — как есть.
- `URL`, `START_TIME`, `END_TIME` — из самого свежего вхождения по `DATE`.
- `DATE` — самого свежего вхождения (для отображения в формате «DD месяца», например «19 мая»).
- `PARTICIPANTS` — объединение всех уникальных ФИО за все вхождения.

Уникальные одноразовые встречи остаются как есть.

## Шаг 6. Группировка задач по проектам — строгие правила

Для каждой уникальной задачи (после Шага 2) определи группу.

### Алгоритм определения проекта задачи

1. Возьми FINAL_PROJECT из самого свежего упоминания задачи.
2. Если FINAL_PROJECT не пуст → задача идёт в группу «Проект: {FINAL_PROJECT}».
3. Если FINAL_PROJECT пуст / null → проверь предыдущие упоминания задачи (от свежих к старым), возьми первое непустое значение PROJECT и используй как FINAL_PROJECT.
4. Если ни в одном упоминании задачи проект не указан → задача идёт в группу «Задачи без проекта».

### Критическое правило (нарушение = ошибка отчёта)

**Каждая уникальная задача (по URL) должна появиться РОВНО В ОДНОЙ группе** в секциях «Завершённые» и «В работе».

- НИКОГДА не дублируй одну и ту же задачу (по URL) в две разные группы проектов.
- НИКОГДА не клади одну и ту же задачу одновременно в «Задачи без проекта» И в какой-либо проект.
- Если по ходу работы тебе кажется, что задача относится к двум проектам — это значит, что Шаг 2 был выполнен некорректно. Перевыполни Шаг 2: одна задача = один URL = один FINAL_PROJECT.

### Порядок групп в отчёте

1. «Задачи без проекта» (если есть) — всегда первая.
2. Далее проекты по убыванию суммарного количества задач в группе (Завершённые + В работе).
3. При равенстве количества — по алфавиту названия проекта.

Внутри каждой группы выводи только подсекции, в которых есть задачи: «Завершённые» и/или «В работе». Внутри подсекции — порядок задач от свежей `DATE` последнего упоминания к старой.

## Шаг 7. Подсчёт итогов

- `X` = количество уникальных задач с финальным статусом «Завершено».
- `Y` = количество уникальных задач с финальным статусом «В работе».
- `Z` = количество уникальных задач с финальным статусом «Требуют внимания».
- В строке «Завершено — X задач, в работе — Y задач, требуют внимания — Z задач» слово «задача» согласуй с числом по русской норме: `1, 21, 31…` → `задача`; `2–4, 22–24…` → `задачи`; `0, 5–20, 25–30…` → `задач`. Согласование применяется ко ВСЕМ трём числам, включая `Z` у «требуют внимания» — пропускать слово нельзя.
- `A ч B мин` = сумма длительностей **всех** встреч из DAILY_SUMMARIES (до дедупликации). Если еженедельный stand-up длился по 30 минут 4 раза — это 2 ч 0 мин в итоге, даже если в списке встреч он показан одной строкой.
- **Фокус периода** — 2–3 предложения о тематике работы. Опирайся на: проекты с наибольшим объёмом задач, повторяющиеся ключевые слова в названиях задач, тематики встреч за период. Конкретно, без воды.

