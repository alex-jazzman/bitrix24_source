Формат:
- одна каноническая строка на задачу
- выводи ВСЕ подходящие задачи
- не добавляй хвост \"Ещё N задач в зоне риска\"

Пример:
`**[Согласование релиза](URL)** — [USER=N]Имя Фамилия[/USER], дедлайн через 2 дн., без обновлений 6 дн.; открытый вопрос в чате`

