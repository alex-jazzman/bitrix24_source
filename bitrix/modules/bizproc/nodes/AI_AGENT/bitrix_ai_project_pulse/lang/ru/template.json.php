## Шаг 2: Классификация задач в блоки

Классифицировать задачи строго по правилам ниже. Каждая задача попадает максимум в один блок. Приоритет блоков при пересечении: Просроченные > В зоне риска > Требующие внимания.

### Блок «Просроченные задачи»

Критерий: IS_OVERDUE = true.
Сортировка: PRIORITY по убыванию (2 -> 1 -> 0), затем по количеству дней просрочки по убыванию.

### Блок «Задачи в зоне риска»

Критерий: ВСЕ условия выполнены:
- DEADLINE задан
- До DEADLINE осталось от 1 до 3 рабочих дней (пн-пт)
- IS_OVERDUE = false
- Признак слабого прогресса: DAYS_WITHOUT_UPDATES >= 5

Сортировка: по количеству дней до дедлайна по возрастанию.

### Блок «Задачи, требующие внимания»

Задача попадает в этот блок, если она не попала в «Просроченные» и «В зоне риска» и подходит под один из 4 паттернов (проверять в указанном порядке, первое совпадение определяет паттерн):

**Паттерн 1 — Важная задача без движения:**
- PRIORITY = 2
- DAYS_WITHOUT_UPDATES >= 10
Описание проблемы: «важная задача, без обновлений [N] рабочих дней»

**Паттерн 2 — Задача зависла на контроле:**
- STATUS_CODE = 4
- DAYS_ON_CONTROL >= 5 (поле может отсутствовать; если отсутствует — считать 0)
Описание проблемы: «ждёт контроля [N] рабочих дней»

**Паттерн 3 — Важная задача без срока:**
- PRIORITY = 2
- DEADLINE отсутствует (null)
Описание проблемы: «важная задача без крайнего срока»

**Паттерн 4 — Забытая задача:**
- DEADLINE отсутствует (null)
- Задача создана более 30 дней назад (определить по самому раннему сообщению «создал задачу» в CHAT_INFO или по ACTIVITY_DATE, если CHAT_INFO пуст)
- DAYS_WITHOUT_UPDATES >= 10
Описание проблемы: «без обновлений [N] рабочих дней, создана более месяца назад»

