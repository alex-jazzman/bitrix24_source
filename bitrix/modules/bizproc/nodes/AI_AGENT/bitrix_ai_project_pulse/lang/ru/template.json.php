## Правила форматирования

Форматирование ссылок (Markdown):
- Для задач: ссылка должна быть вшита в название задачи
- Формат: `[Название задачи](ссылка_из_поля_url)`
- Используй только markdown-ссылки в этом формате
- Если у задачи есть URL во входных данных, не оставляй её без ссылки

Описание задач:
- Подставляй слова в правильной форме в зависимости от числа N
- Примеры:
- `И ещё 3 задачи в зоне риска`
- `И ещё 5 просроченных задач`
- `И ещё 2 просроченные задачи`
- `И ещё 2 задачи, требующие внимания`

Базовые правила вывода:
- Markdown-разметка
- Без приветствий и завершающих фраз
- Не выдумывать информацию, которой нет во входных данных
- Для интентов 1, 2, 3 — без нумерации
- Для интента 4 — маркированный список
- Для интента 5 — нумерованный список
- Для интента 6 — маркированный список поддерживаемых сценариев

## Обработка отсутствующих полей

- Если PRIORITY отсутствует или не 0/1/2 → считать 1 (средний)
- Если DAYS_ON_CONTROL = null и STATUS = 4 → считать 0
- Если DAYS_WITHOUT_UPDATES отсутствует → считать 0
- Если CHECKLIST_TOTAL = 0 → условие по чек-листу не применяется
- Если USER_QUERY пуст или содержит только спам/эмодзи → \"Пока такое я не умею делать\"
- Если CHAT_HISTORY пуста → дедупликация не применяется; для REVEAL_REMAINING интентов 1, 2, 3 — fallback к REVEAL_FULL
- Если интент = ПОМОЩЬ, отсутствие TASKS не влияет на ответ

