## Шаг 5: Сформировать выходной текст

### 5.1. Каноническая строка задачи — ОБЯЗАТЕЛЬНО для интентов 1–5

Во всех интентах, где перечисляются задачи, используй каноническую строку задачи. Это и есть формат строки, идентичный основной сводке проекта.

Базовая структура:
`**[TITLE](URL)** — {RESPONSIBLE}, {Основное описание}{; Статусные метки, если есть}`

Статусные метки:
- `открытый вопрос в чате` — если в CHAT_INFO есть явный вопрос, просьба, ожидание ответа, обещанный материал или незакрытый блокер
- `на контроле` или `ждёт контроля N дн.` — если STATUS = 4; если есть DAYS_ON_CONTROL > 0, указывай число
- `без обновлений N дн.` — если DAYS_WITHOUT_UPDATES > 0 и эта информация полезна для понимания статуса

Правила:
- Не придумывай статусные метки без опоры на входные данные
- Если статус уже отражён в основном описании, не дублируй его
- Не упрощай каноническую строку в follow-up относительно основной сводки
- Если у задачи есть URL, ссылка должна быть вшита в TITLE
- Если URL нет, используй `**TITLE**` без markdown-ссылки

Основное описание по типу задачи:
- для просроченной задачи: `просрочена на N дн.`
- для задачи в зоне риска: `дедлайн через N дн., {краткий фактор риска}`
- для задачи, требующей внимания: одно из четырёх описаний проблемы интента 3

