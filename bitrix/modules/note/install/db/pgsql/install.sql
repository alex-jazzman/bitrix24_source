CREATE TABLE IF NOT EXISTS b_note_collection (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	NAME varchar(255) NOT NULL,
	CREATED_BY int NOT NULL,
	POSITION int NOT NULL DEFAULT 0,
	POLICY_LEVEL int NOT NULL DEFAULT 0,
	IS_ARCHIVED char(1) NOT NULL DEFAULT 'N',
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UPDATED_BY int NOT NULL,
	UPDATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTE_COLL_SORT ON b_note_collection (IS_ARCHIVED, POSITION, ID);

CREATE TABLE IF NOT EXISTS b_note_document (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	COLLECTION_ID int NOT NULL,
	PARENT_ID int NULL,
	TITLE varchar(255) NOT NULL,
	MARKDOWN text NOT NULL,
	YJS_STATE text DEFAULT NULL,
	CONTENT_FORMAT varchar(5) NOT NULL DEFAULT 'yjs',
	POSITION int NOT NULL DEFAULT 0,
	IS_ARCHIVED char(1) NOT NULL DEFAULT 'N',
	ARCHIVED_AT timestamp NULL,
	ARCHIVED_BY int NULL,
	CREATED_BY int NOT NULL,
	UPDATED_BY int NOT NULL,
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	UPDATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTE_DOC_BRANCH ON b_note_document (COLLECTION_ID, PARENT_ID, IS_ARCHIVED, POSITION, ID);
CREATE INDEX IF NOT EXISTS IX_NOTE_DOC_BRANCH_REORDER ON b_note_document (COLLECTION_ID, PARENT_ID, POSITION);
CREATE INDEX IF NOT EXISTS IX_NOTE_DOC_ARCHIVE ON b_note_document (IS_ARCHIVED, ARCHIVED_AT, ID);

CREATE TABLE IF NOT EXISTS b_note_document_file (
	DOCUMENT_ID int NOT NULL,
	FILE_ID int NOT NULL,
	CREATED_BY int NOT NULL,
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (DOCUMENT_ID, FILE_ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS IX_NOTE_DOC_FILE_UNIQ_FILE ON b_note_document_file (FILE_ID);

CREATE TABLE IF NOT EXISTS b_note_role (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	NAME varchar(250) NOT NULL,
	PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS b_note_role_relation (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	ROLE_ID int NOT NULL,
	RELATION varchar(8) NOT NULL DEFAULT '',
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTE_ROLE_REL ON b_note_role_relation (ROLE_ID, RELATION);

CREATE TABLE IF NOT EXISTS b_note_permission (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	ROLE_ID int NOT NULL,
	PERMISSION_ID varchar(32) NOT NULL DEFAULT '0',
	VALUE int NOT NULL DEFAULT 0,
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTE_PERM ON b_note_permission (ROLE_ID, PERMISSION_ID, VALUE);

CREATE TABLE IF NOT EXISTS b_note_collection_access (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	COLLECTION_ID int NOT NULL,
	SUBJECT_CODE varchar(50) NOT NULL,
	LEVEL int NOT NULL,
	CREATED_BY int NOT NULL,
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS IX_NOTE_COLLECTION_ACCESS_UNIQ ON b_note_collection_access (COLLECTION_ID, SUBJECT_CODE);
CREATE INDEX IF NOT EXISTS IX_NOTE_COLL_ACCESS_SUBJECT ON b_note_collection_access (SUBJECT_CODE, COLLECTION_ID, LEVEL);

CREATE TABLE IF NOT EXISTS b_note_document_access (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	DOCUMENT_ID int NOT NULL,
	SUBJECT_CODE varchar(50) NOT NULL,
	LEVEL int NOT NULL,
	CREATED_BY int NOT NULL,
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS IX_NOTE_DOCUMENT_ACCESS_UNIQ ON b_note_document_access (DOCUMENT_ID, SUBJECT_CODE);
CREATE INDEX IF NOT EXISTS IX_NOTE_DOC_ACCESS_SUBJECT ON b_note_document_access (SUBJECT_CODE, DOCUMENT_ID, LEVEL);

CREATE TABLE IF NOT EXISTS b_note_import_session (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	CREATED_BY int NOT NULL,
	STATUS varchar(32) NOT NULL DEFAULT 'connecting',
	PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS b_note_import_map (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	SOURCE_TYPE varchar(32) NOT NULL,
	EXTERNAL_ID varchar(128) NOT NULL,
	URL_ID varchar(16) NULL DEFAULT NULL,
	DOCUMENT_ID int NULL,
	COLLECTION_ID int NULL,
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_IMPORT_MAP ON b_note_import_map (SOURCE_TYPE, EXTERNAL_ID);
CREATE INDEX IF NOT EXISTS IX_IMPORT_MAP_URL_ID ON b_note_import_map (SOURCE_TYPE, URL_ID);

CREATE TABLE IF NOT EXISTS b_note_unresolved_mention (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	DOCUMENT_ID int NOT NULL,
	SOURCE_TYPE varchar(32) NOT NULL,
	EXTERNAL_ID varchar(128) NOT NULL,
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_UNRESOLVED ON b_note_unresolved_mention (SOURCE_TYPE, EXTERNAL_ID);
CREATE INDEX IF NOT EXISTS IX_UNRESOLV_DOC ON b_note_unresolved_mention (DOCUMENT_ID);

CREATE TABLE IF NOT EXISTS b_note_document_updates (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	DOCUMENT_ID int NOT NULL,
	USER_ID int NOT NULL,
	PATCH text NOT NULL,
	CREATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTE_DOC_UPD_DOCID ON b_note_document_updates (DOCUMENT_ID, ID);

CREATE TABLE IF NOT EXISTS b_note_document_search (
	ID int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	DOCUMENT_ID int NOT NULL,
	BODY text NOT NULL,
	UPDATED_AT timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_NOTE_DOCUMENT_SEARCH_DOCUMENT ON b_note_document_search (DOCUMENT_ID);
CREATE INDEX IF NOT EXISTS FT_NOTE_DOCUMENT_SEARCH_BODY ON b_note_document_search USING GIN (to_tsvector('english', BODY));

CREATE TABLE IF NOT EXISTS b_note_recycle_bin (
	ID bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	DOCUMENT_ID int NOT NULL,
	TRASHED_AT timestamp NOT NULL,
	TRASHED_BY int NOT NULL,
	ORIGIN varchar(40) NOT NULL,
	PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_NOTE_RECYCLEBIN_DOC ON b_note_recycle_bin (DOCUMENT_ID);
CREATE INDEX IF NOT EXISTS IX_NOTE_RECYCLEBIN_AT_ID ON b_note_recycle_bin (TRASHED_AT, ID);
CREATE INDEX IF NOT EXISTS IX_NOTE_RECYCLEBIN_BY ON b_note_recycle_bin (TRASHED_BY);
